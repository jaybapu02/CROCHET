/** One selectable way of buying a product, e.g. { label: "Pair", price: 299 }. */
export type ProductVariant = {
  /** Unit label shown with the price — "Single", "Pair", … */
  label: string;
  /** Price in INR for this variant. */
  price: number;
};

export type Product = {
  id: string;
  slug: string;
  name: string;
  /** Category slug — must match an entry in data/categories.ts */
  category: string;
  /**
   * Price in INR (sample data).
   * `null` = no price supplied yet — the site shows "Contact for Price"
   * instead of an invented amount.
   */
  price: number | null;
  /**
   * Optional unit/size note shown right after the price, e.g.
   * "per tulip", "(Big Size)", "(Normal Size)".
   */
  priceNote?: string;
  /**
   * Optional selectable variants (Single / Pair, …). When present every
   * variant price is shown as "₹160 — Single", "₹299 — Pair" and the
   * customer picks one on the product page and the order form.
   * `price` stays the default (first) variant price.
   */
  variants?: ProductVariant[];
  shortDescription: string;
  description: string;
  images: string[];
  materials: string;
  size: string;
  care: string;
  leadTime: string;
  featured: boolean;
  bestSeller?: boolean;
  available: boolean;
  customisable?: boolean;
};

